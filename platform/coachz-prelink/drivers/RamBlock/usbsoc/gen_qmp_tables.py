#!/usr/bin/env python3
"""Regenerate coachz_qmp_tables.h from a Linux tree at the pinned commit (SOURCES.md).

usage: python3 -I gen_qmp_tables.py LINUX_TREE OUTPUT_HEADER

The sc7180 USB3 tables of drivers/phy/qualcomm/phy-qcom-qmp-combo.c are taken as text, compiled on the host against
the same driver's v3 register headers (BIT/GENMASK defined here) and printed as numbers, so no register name is
transcribed by hand. The QUSB2 v2 table is small and stays hand-written in coachz_usb_proto.h.
"""
import re, subprocess, sys, tempfile
from pathlib import Path

COMMIT = '6628e7d4c6b25c8d18f1345e3a20d21829aae7e4'
TABLES = ['qmp_v3_usb3_serdes_tbl', 'qmp_v3_usb3_tx_tbl', 'qmp_v3_usb3_rx_tbl', 'qmp_v3_usb3_pcs_tbl']
HEADERS = ['phy-qcom-qmp-qserdes-com-v3.h', 'phy-qcom-qmp-qserdes-txrx-v3.h', 'phy-qcom-qmp-pcs-v3.h']

tree, out = Path(sys.argv[1]), Path(sys.argv[2])
qmp = tree / 'drivers/phy/qualcomm'
text = (qmp / 'phy-qcom-qmp-combo.c').read_text()
bodies = {}
for name in TABLES:
    m = re.search(r'static const struct qmp_phy_init_tbl ' + name + r'\[\] = \{(.*?)\n\};', text, re.S)
    if not m:
        raise SystemExit('missing ' + name)
    bodies[name] = m.group(1)

prog = ['#include <stdio.h>', '#define BIT(n) (1u << (n))', '#define GENMASK(h, l) (((~0u) << (l)) & (~0u >> (31 - (h))))']
prog += ['#include "%s"' % h for h in HEADERS]
prog += ['struct t { unsigned offset, val; const char *name; unsigned char lane_mask; };',
         '#define QMP_PHY_INIT_CFG(o, v) { o, v, #o, 0xff }', '#define QMP_PHY_INIT_CFG_LANE(o, v, l) { o, v, #o, l }']
for name, body in bodies.items():
    prog.append('static const struct t %s[] = {%s};' % (name, body))
prog.append('int main(void) {')
for name in TABLES:
    prog.append('  printf("static const struct cu_qmp_reg cu_%s[] = {\\n");' % name[4:])
    prog.append('  for (unsigned i = 0; i < sizeof(%s) / sizeof(%s[0]); i++) printf("    { 0x%%04x, 0x%%02x, 0x%%02x }, /* %%s */\\n", %s[i].offset, %s[i].val, %s[i].lane_mask, %s[i].name);' % ((name,) * 6))
    prog.append('  printf("};\\n");')
prog.append('  return 0; }')
with tempfile.TemporaryDirectory() as d:
    src, exe = Path(d) / 'gen.c', Path(d) / 'gen'
    src.write_text('\n'.join(prog) + '\n')
    subprocess.run(['cc', '-std=c11', '-w', '-I', str(qmp), str(src), '-o', str(exe)], check=True)
    tables = subprocess.run([str(exe)], check=True, capture_output=True, text=True).stdout
out.write_text('/* SPDX-License-Identifier: BSD-2-Clause */\n'
               '/* Generated by gen_qmp_tables.py from Linux %s drivers/phy/qualcomm/phy-qcom-qmp-combo.c\n'
               '   (sc7180_usb3dpphy_cfg USB3 tables) with its v3 register headers. Do not edit; regenerate.\n'
               '   Each entry: offset within its block, value, lane mask (0xff: every lane). */\n'
               '#ifndef COACHZ_QMP_TABLES_H\n#define COACHZ_QMP_TABLES_H\n\n'
               'struct cu_qmp_reg { unsigned short offset; unsigned char val, lane_mask; };\n\n%s\n#endif\n' % (COMMIT, tables))
print(out, sum(tables.count('{ 0x') for _ in [0]), 'entries')
