def require(v,why):
    if not v:raise SystemExit(why)


def adrp(pc,word):
    imm=((word>>5)&0x7ffff)<<2|((word>>29)&3)
    if imm&(1<<20):imm-=1<<21
    return (pc&~4095)+(imm<<12)


def branch(pc,word):
    value=word&0x3ffffff
    return pc+4*(value-(1<<26) if value&(1<<25) else value)


def qualify(reference):
    """The original class's bindings and vtable, after every check against the reference kernel."""
    from native_prelink import macho,backed_offset,exports
    b=Path(reference).read_bytes();m=macho(b);plan=json.loads(Path(reference).with_suffix('.json').read_text())
    def read(a,n):
        at=backed_offset(m['segments'],a,n,len(b));return b[at:at+n]
    def word(a):return struct.unpack('<I',read(a,4))[0]
    def stub(a):
        # adrp x16, page; ldr x16, [x16, #off]; br x16: the GOT entry it jumps through.
        first,second,third=struct.unpack('<3I',read(a,12))
        require(first&0x9f00001f==0x90000010 and second&0xffc003ff==0xf9400210 and third==0xd61f0200,'Original kext stub')
        return struct.unpack('<Q',read(adrp(a,first)+((second>>10)&4095)*8,8))[0]
    names={n:a for a,ns in exports(b,m).items() for n in ns}
    require(plan['original_executable_sha256']['com.apple.driver.AppleARMPlatform']==PLATFORM_TEXT_SHA,
            'Exact original AppleARMPlatform of this OS profile')
    e=next(e for e in plan['extents'] if e['module']=='com.apple.driver.AppleARMPlatform' and e['segment']=='__TEXT_EXEC')
    require(hashlib.sha256(read(e['va'],e['size'])).hexdigest()==PLATFORM_TEXT_SHA,'Complete original AppleARMPlatform instructions')
    # The metaclass: OSMetaClass(this = METACLASS, "AppleARMBacklight", &IOService::gMetaClass, 0x370).
    init=struct.unpack('<10I',read(STATIC_INIT,40))
    require(adrp(STATIC_INIT+8,init[2])+((init[3]>>10)&4095)==METACLASS and
            adrp(STATIC_INIT+16,init[4])+((init[5]>>10)&4095)==CLASS_NAME and read(CLASS_NAME,18)==b'AppleARMBacklight\0','Original metaclass object and name')
    got=adrp(STATIC_INIT+24,init[6])+((init[7]>>10)&4095)*8
    require(struct.unpack('<Q',read(got,8))[0]==names['__ZN9IOService10gMetaClassE'],'Original superclass is IOService')
    require(init[8]==0x52806e03,'Original 0x370-byte instance size')
    require(stub(branch(STATIC_INIT+36,init[9]))==names['__ZN11OSMetaClassC2EPKcPKS_j'],'Original metaclass constructor call')
    # The protected constructor calls the native IOService constructor, stores the vptr and clears its own fields only.
    require(read(CONSTRUCTOR,0x34)==bytes.fromhex('fd7bbfa9fd030091e14900940899009008613491080000f91f6000f91f8008391f9401f91fb001f91f6803b9fd7bc1a8c0035fd6'),
            'Original protected constructor')
    require(stub(branch(CONSTRUCTOR+8,word(CONSTRUCTOR+8)))==names['__ZN9IOServiceC2EPK11OSMetaClass'],'Native protected constructor binding')
    require(adrp(CONSTRUCTOR+12,word(CONSTRUCTOR+12))+((word(CONSTRUCTOR+16)>>10)&4095)==VPTR,'Original constructor vptr')
    require(word(DESTRUCTOR)&0xfc000000==0x14000000 and stub(branch(DESTRUCTOR,word(DESTRUCTOR)))==names['__ZN9IOServiceD2Ev'],
            'Original protected destructor is the native IOService one')
    methods=struct.unpack(f'<{SLOTS}Q',read(VPTR,SLOTS*8))
    base=struct.unpack('<168Q',read(names['__ZTV9IOService']+16,168*8))
    require(all(methods) and read(VPTR+SLOTS*8,16)==bytes(16) and names['___cxa_pure_virtual'] not in methods,
            'Original 169-slot concrete vtable')
    require([i for i in range(168) if methods[i]!=base[i]]==ORIGINAL_OVERRIDES,'Exact original IOService overrides')
    bindings={'__ZN17AppleARMBacklightC2EPK11OSMetaClass':CONSTRUCTOR,'__ZN17AppleARMBacklightD2Ev':DESTRUCTOR,
              '__ZN17AppleARMBacklight10gMetaClassE':METACLASS,'__ZTV17AppleARMBacklight':VPTR-16}
    return names,methods,bindings


def main():
    from native_prelink import macho
    from coachz_late_init import stage_initializer
    out=ROOT/'build/coachz-backlight';out.mkdir(parents=True,exist_ok=True)
    def run(cmd,**kw):return subprocess.check_output([str(x) for x in cmd],timeout=90,**kw)
    def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
    reference=Path(os.environ['COACHZ_DISPLAY_REFERENCE'])
    names,methods,bindings=qualify(reference)
    (out/'OriginalAppleARMBacklightABI.h').write_text(HEADER)
    record=json.loads((ROOT/'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/iokit/DEVELOPMENT/IOPlatformExpert.cpo.json').read_text().strip().rstrip(','))
    def compile_glue(source,output):
        args=record['arguments'];cmd=[];i=0
        while i<len(args):
            value=args[i]
            if value==record['file']:cmd.append(str(source))
            elif value in ('-o','-MF','-MT','-MJ'):
                if value=='-o':cmd+=['-o',str(output)]
                i+=1
            elif value=='-Xclang' and args[i+1].startswith('-W'):i+=1
            elif not value.startswith('-W'):cmd.append(value)
            i+=1
        cmd+=['-Wall','-Wextra','-Werror','-Wno-unused-parameter','-Wno-unnecessary-virtual-specifier','-Wno-c99-designator',
              '-Wno-reorder-init-list','-Wno-deprecated-enum-enum-conversion','-I',str(out),'-I',str(ROOT/'.cache/xnu-work/bsd/dev')]
        run(cmd,cwd=record['directory'])
    source=ROOT/'kits/coachz/CoachzBacklight.cpp';start=ROOT/'kits/coachz/CoachzBacklightStart.cpp'
    obj=out/'CoachzBacklight.o';compile_glue(source,obj);compile_glue(start,out/'CoachzBacklightStart.o')
    raw=obj.read_bytes();om=macho(raw)
    st=next(p for c,p,_ in om['commands'] if c==2);sy,count,strings,_=struct.unpack_from('<4I',raw,st+8);symbols=[]
    for i in range(count):
        ix,kind,section,_,va=struct.unpack_from('<IBBHQ',raw,sy+i*16)
        symbols.append((raw[strings+ix:raw.index(b'\0',strings+ix)].decode(),va,kind))
    vt=next(va for name,va,_ in symbols if name=='__ZTV15CoachzBacklight');relocations={}
    for segment in om['segments']:
        for sec in segment['sections']:
            if sec['va']<=vt<sec['va']+sec['size']:
                ro,rc=struct.unpack_from('<2I',raw,sec['command_offset']+56)
                for i in range(rc):
                    offset,bits=struct.unpack_from('<2I',raw,ro+i*8)
                    if bits>>27&1 and bits>>28==0 and bits>>25&3==3:relocations[sec['va']+offset]=symbols[bits&0xffffff][0]
    compiled=[relocations.get(vt+16+i*8) for i in range(SLOTS)]
    require(all(compiled) and vt+16+SLOTS*8 not in relocations,'Compiled exact 169-slot vtable')
    owned=[]
    for i,name in enumerate(compiled):
        if name.startswith(('__ZN15CoachzBacklight','__ZNK15CoachzBacklight')):owned.append(i)
        elif '17AppleARMBacklight' in name:
            require(i==168,'Only the original class slot 168 dispatches to original code');bindings[name]=methods[i]
        else:require(i<168 and names.get(name)==methods[i],'Actual inherited native method '+str(i))
    # Every original override is replaced, so no original AppleARMBacklight method runs on this object's uninitialized state.
    require(owned==ORIGINAL_OVERRIDES,'Exactly the original overrides are owned')
    undefined={n for n,_,k in symbols if k==1 and '17AppleARMBacklight' in n}
    require(undefined<=set(bindings) and {'__ZN17AppleARMBacklightC2EPK11OSMetaClass','__ZN17AppleARMBacklightD2Ev',
            '__ZN17AppleARMBacklight10gMetaClassE'}<=undefined,'All original-class imports qualified')
    asm=out/'backlight-original-bindings.S';asm.write_text(''.join(f'.globl {n}\n.set {n}, {a:#x}\n' for n,a in sorted(bindings.items())))
    sdk=run(['xcrun','--sdk','iphoneos','--show-sdk-path'],text=True).strip()
    run(['xcrun','clang','-target','arm64-apple-ios17.0','-isysroot',sdk,'-c',asm,'-o',out/'backlight-original-bindings.o'])
    late=out/'CoachzBacklight.late.o'
    late.write_bytes(stage_initializer(raw,'__GLOBAL__sub_I_CoachzBacklight.cpp'))
    def code(data,info):
        sec=next(s for g in info['segments'] for s in g['sections'] if s['name']=='__text');return data[sec['fileoff']:sec['fileoff']+sec['size']]
    require(code(raw,om)==code(late.read_bytes(),macho(late.read_bytes())),'Owned code unchanged by deferred metaclass registration')
    archive=out/'libCoachzBacklight.a';archive.unlink(missing_ok=True)
    run(['xcrun','ar','rcs',archive,late,out/'backlight-original-bindings.o',out/'CoachzBacklightStart.o'])
    report={'archive_sha256':sha(archive),'reference_sha256':sha(reference),'original_text_sha256':PLATFORM_TEXT_SHA,'original_slots':SLOTS,
            'owned_slots':owned,'bindings':{n:hex(v) for n,v in bindings.items()},
            'source_sha256':{str(p.relative_to(ROOT)):sha(p) for p in [source,start]},'hardware_accepted':False}
    (out/'coachz-report.json').write_text(json.dumps(report,indent=2)+'\n')
    print('Coachz: original AppleARMBacklight ABI bound and EC backlight built; hardware not accepted')


if __name__=='__main__':
    main()
