import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'kits/XnuPrelink'))
PLATFORM_TEXT_SHA='6af4faa236f7adc0d297d99eae53ce7590bc250b76647619128c62c8165df052'
CONSTRUCTOR,DESTRUCTOR,METACLASS,VPTR=0xfffffff0049abc1c,0xfffffff0049abc84,0xfffffff006ade638,0xfffffff005ccbd18
STATIC_INIT,CLASS_NAME=0xfffffff0049b52b8,0xfffffff004291985
