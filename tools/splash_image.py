#!/usr/bin/env python3
"""Convert a square PNG into the boot picture boot/xnu_screen.c draws."""
# SPDX-License-Identifier: BSD-2-Clause
import argparse
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
ON_SCREEN = 512   # pixels; the data is scaled up by a whole factor
NEAR_WHITE = 225


def decode_png(data):
    """An 8-bit, non-interlaced RGB or RGBA PNG as a width, a height and rows of (r, g, b, a)."""
    if data[:8] != b'\x89PNG\r\n\x1a\n':
        raise ValueError('not a PNG')
    offset, compressed = 8, b''
    while offset < len(data):
        size, kind = struct.unpack('>I4s', data[offset:offset + 8])
        chunk = data[offset + 8:offset + 8 + size]
        offset += 12 + size
        if kind == b'IHDR':
            width, height, depth, color, _, _, interlace = struct.unpack('>IIBBBBB', chunk)
            if depth != 8 or color not in (2, 6) or interlace:
                raise ValueError('need an 8-bit, non-interlaced RGB or RGBA PNG')
        elif kind == b'IDAT':
            compressed += chunk
    raw, step = zlib.decompress(compressed), 3 if color == 2 else 4
    stride, rows, previous, at = width * step, [], bytes(width * step), 0
    for _ in range(height):
        kind, line = raw[at], bytearray(raw[at + 1:at + 1 + stride])
        at += 1 + stride
        for i in range(stride):
            left = line[i - step] if i >= step else 0
            up = previous[i]
            corner = previous[i - step] if i >= step else 0
            if kind == 1:
                line[i] = (line[i] + left) & 255
            elif kind == 2:
                line[i] = (line[i] + up) & 255
            elif kind == 3:
                line[i] = (line[i] + (left + up) // 2) & 255
            elif kind == 4:
                guess = left + up - corner
                near = min((abs(guess - left), 0, left), (abs(guess - up), 1, up), (abs(guess - corner), 2, corner))
                line[i] = (line[i] + near[2]) & 255
        rows.append([(line[i], line[i + 1], line[i + 2], line[i + 3] if step == 4 else 255) for i in range(0, stride, step)])
        previous = line
    return width, height, rows


def cut_white(width, height, rows):
    """Clear the near-white area reached from the border or from transparency; white inside the picture stays."""
    seen = [[False] * width for _ in range(height)]
    def white(x, y):
        return min(rows[y][x][:3]) >= NEAR_WHITE
    stack = [(x, y) for y in range(height) for x in range(width)
             if rows[y][x][3] < 16 or (white(x, y) and (x in (0, width - 1) or y in (0, height - 1)))]
    while stack:
        x, y = stack.pop()
        if seen[y][x]:
            continue
        seen[y][x] = True
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < width and 0 <= ny < height and not seen[ny][nx] and white(nx, ny):
                stack.append((nx, ny))
    return [[(0, 0, 0, 0) if seen[y][x] else rows[y][x] for x in range(width)] for y in range(height)]


def on_black(pixel):
    r, g, b, a = pixel
    return (r * a // 255) << 16 | (g * a // 255) << 8 | (b * a // 255)


def header(size, rows):
    values = [on_black(pixel) for row in rows for pixel in row]
    lines = [','.join('0x%06x' % value for value in values[i:i + 12]) for i in range(0, len(values), 12)]
    return ('/* Generated by tools/splash_image.py. */\n'
            f'#define SPLASH_SIZE {size}u\n#define SPLASH_SCALE {ON_SCREEN // size}u\n'
            f'static const uint32_t splash_pixels[{size * size}]={{\n' + ',\n'.join(lines) + '\n};\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('image', type=Path)
    parser.add_argument('--output', type=Path, default=ROOT / 'boot/splash_data.h')
    args = parser.parse_args()
    width, height, rows = decode_png(args.image.read_bytes())
    if width != height or not 1 <= width <= ON_SCREEN:
        raise SystemExit(f'need a square picture of at most {ON_SCREEN} pixels, got {width}x{height}')
    args.output.write_text(header(width, cut_white(width, height, rows)))
    print(f'{args.output.name}: {width}x{height}, {ON_SCREEN // width} times larger on screen')


if __name__ == '__main__':
    main()
